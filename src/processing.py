"""
Модуль для обработки банковских операций.

Содержит функции для фильтрации и сортировки списка операций.
"""

from typing import List, Dict, Any


def filter_by_state(data: List[Dict[str, Any]], state: str = 'EXECUTED') -> List[Dict[str, Any]]:
    """
    Фильтрует список словарей банковских операций по указанному статусу.

    Функция проходит по всем элементам входного списка и возвращает только те
    операции, у которых значение ключа 'state' совпадает с заданным статусом.

    Параметры:
    ----------
    data : list of dict
        Список словарей, каждый из которых представляет банковскую операцию.
        Каждый словарь ДОЛЖЕН содержать ключ 'state' (str), иначе операция
        будет исключена из результата.
    state : str, optional
        Статус для фильтрации операций. По умолчанию 'EXECUTED'.
        Типичные значения: 'EXECUTED', 'CANCELED', 'PENDING'.

    Возвращаемое значение:
    ----------------------
    list of dict
        Новый список, содержащий только те операции из data,
        у которых значение ключа 'state' равно параметру state.
        Порядок элементов сохраняется.

    Примеры:
    --------
    >>> operations = [
    ...     {"id": 1, "state": "EXECUTED", "amount": 1000},
    ...     {"id": 2, "state": "CANCELED", "amount": 500},
    ...     {"id": 3, "state": "EXECUTED", "amount": 750}
    ... ]
    >>> filter_by_state(operations)
    [{"id": 1, "state": "EXECUTED", "amount": 1000}, {"id": 3, "state": "EXECUTED", "amount": 750}]

    Примечания:
    -----------
    - Функция не изменяет исходный список data
    - Если ключ 'state' отсутствует, операция не попадает в результат
    """
    result = []
    for item in data:
        if item.get('state') == state:
            result.append(item)
    return result


def sort_by_date(data: List[Dict[str, Any]], reverse: bool = True) -> List[Dict[str, Any]]:
    """
    Сортирует список банковских операций по дате.

    Функция сортирует операции на основе значения ключа 'date' в каждом словаре.
    Сортировка стабильная (сохраняет порядок равных элементов).

    Параметры:
    ----------
    data : list of dict
        Список словарей, каждый из которых представляет банковскую операцию.
        Каждый словарь ДОЛЖЕН содержать ключ 'date' со значением в формате
        ISO 8601 (например, '2024-01-15T10:30:00' или '2024-01-15').
        Если ключ 'date' отсутствует, используется пустая строка (такие элементы
        попадут в начало при reverse=False или в конец при reverse=True).
    reverse : bool, optional
        Определяет порядок сортировки:
        - True (по умолчанию) — сортировка по убыванию (новые даты первыми)
        - False — сортировка по возрастанию (старые даты первыми)

    Возвращаемое значение:
    ----------------------
    list of dict
        Новый отсортированный список операций. Исходный список data не изменяется.

    Примеры:
    --------
    >>> operations = [
    ...     {"id": 1, "date": "2024-01-15T10:00:00"},
    ...     {"id": 2, "date": "2024-01-10T14:30:00"},
    ...     {"id": 3, "date": "2024-01-20T09:15:00"}
    ... ]
    >>> sort_by_date(operations)
    [
        {"id": 3, "date": "2024-01-20T09:15:00"},
        {"id": 1, "date": "2024-01-15T10:00:00"},
        {"id": 2, "date": "2024-01-10T14:30:00"}
    ]

    >>> sort_by_date(operations, reverse=False)
    [
        {"id": 2, "date": "2024-01-10T14:30:00"},
        {"id": 1, "date": "2024-01-15T10:00:00"},
        {"id": 3, "date": "2024-01-20T09:15:00"}
    ]

    >>> # Смешанные форматы дат (лексикографическое сравнение)
    >>> mix = [
    ...     {"id": 1, "date": "2024-01-15"},
    ...     {"id": 2, "date": "2024-01-15T10:00:00"}
    ... ]
    >>> sort_by_date(mix)
    [
        {"id": 2, "date": "2024-01-15T10:00:00"},
        {"id": 1, "date": "2024-01-15"}
    ]

    Примечания:
    -----------
    - Функция использует лексикографическое сравнение строк, что корректно работает
      для дат в формате ISO 8601 (ГГГГ-ММ-ДД или ГГГГ-ММ-ДДTчч:мм:сс).
    - Функция не изменяет исходный список data, а возвращает новый отсортированный.
    - Элементы без ключа 'date' обрабатываются с помощью get('date', '') и
      будут помещены в начало при reverse=False или в конец при reverse=True.
    """
    return sorted(data, key=lambda x: x.get('date', ''), reverse=reverse)
